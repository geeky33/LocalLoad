function apiTable() {
  const src = read('server/src/routes/index.ts');
  const rows = [];
  // collapse multi-line route registrations
  const flat = src.replace(/\n\s+/g, ' ');
  for (const m of flat.matchAll(/r\.(get|post|put|delete)\(\s*'([^']+)'([^;]*)\);/g)) {
    const [, method, p, rest] = m;
    const access = p.startsWith('/admin') ? 'Admin (JWT + role)' : /requireAuth|reportBase/.test(rest) ? 'Authenticated (JWT)' : 'Public';
    const handler = rest.match(/(\w+)\.(\w+)\s*,?\s*$/)?.[0]?.replace(/,\s*$/, '') ?? '';
    rows.push([method.toUpperCase(), `\`/api${p}\``, access, `\`${handler.trim()}\``]);
  }
  if (!rows.length) fail('no routes found in server/src/routes/index.ts');
  replaceBlock('11-system-architecture.md', 'api', `${GENERATED_NOTE('server/src/routes/index.ts')}\n\n${mdTable(['Method', 'Path', 'Access', 'Handler'], rows, [10, 40, 22, 28])}`);
  return `${rows.length} endpoints`;
}

