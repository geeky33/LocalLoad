/** Parse a Mongoose schema file written in this project's style. */
function parseModel(file) {
  const src = read(file);
  const modelMatch = src.match(/model\('(\w+)',\s*(\w+)\)/);
  if (!modelMatch) fail(`no model('Name', schema) call found in ${file}`);
  const [, modelName, schemaVar] = modelMatch;
  const start = src.indexOf(`const ${schemaVar} = new Schema(`);
  if (start === -1) fail(`schema ${schemaVar} not found in ${file}`);
  const body = src.slice(start);
  const lines = body.split('\n');
  const fields = [];
  let nested = null;
  for (const line of lines.slice(1)) {
    if (/^\s{2}\},\s*$/.test(line) || /^\s{2}\{\s*timestamps/.test(line)) break; // end of field definition object
    const top = line.match(/^ {4}(\w+):\s*(.*)$/);
    const sub = line.match(/^ {6}(\w+):\s*(.*)$/);
    if (top) {
      const [, name, rest] = top;
      if (rest.trim() === '{') {
        nested = { name, type: 'Object', notes: [], children: [] };
        fields.push(nested);
        continue;
      }
      nested = null;
      fields.push(describeField(name, rest));
    } else if (sub && nested) {
      nested.children.push(sub[1]);
    }
  }
  for (const f of fields) if (f.children) f.notes.push(`embedded: ${f.children.join(', ')}`);
  const timestamps = /timestamps:\s*true/.test(body);
  const indexes = [...src.matchAll(/\.index\((\{[^}]*\})(?:,\s*(\{[^}]*\}))?\)/g)].map((m) => ({
    keys: m[1].replace(/\s+/g, ' '),
    unique: /unique:\s*true/.test(m[2] ?? ''),
  }));
  const comments = [...src.matchAll(/^\/\/ (.*)$/gm)].map((m) => m[1]).concat(
    [...src.matchAll(/^\/\*\*?([\s\S]*?)\*\//gm)].map((m) => m[1].replace(/^\s*\* ?/gm, '').trim()),
  );
  return { file, modelName, collection: modelName.toLowerCase() + 's', fields, timestamps, indexes, comments };
}

function describeField(name, rest) {
  const isArray = rest.trim().startsWith('[');
  const ref = rest.match(/ref:\s*'(\w+)'/)?.[1];
  let type = rest.match(/type:\s*([\w.]+)/)?.[1] ?? rest.replace(/[,\s].*$/, '');
  if (type === 'Schema.Types.ObjectId') type = 'ObjectId';
  const notes = [];
  if (/required:\s*true/.test(rest)) notes.push('required');
  if (/unique:\s*true/.test(rest)) notes.push('unique');
  if (/index:\s*true/.test(rest)) notes.push('indexed');
  if (/select:\s*false/.test(rest)) notes.push('hidden by default');
  const en = rest.match(/enum:\s*(\[[^\]]*\]|[A-Z_]+)/)?.[1];
  if (en) notes.push(`enum ${en.startsWith('[') ? en.replace(/'/g, '') : `(${en})`}`);
  const def = rest.match(/default:\s*([^,}]+)/)?.[1]?.trim();
  if (def) notes.push(`default ${def}`);
  const comment = rest.match(/\/\/\s*(.*)$/)?.[1];
  if (comment) notes.push(comment);
  return { name, type: isArray ? `${type}[]` : type, ref, isArray, notes };
}

function databaseDesign() {
  const dir = rel('server/src/models');
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .sort()
    .map((f) => `server/src/models/${f}`);
  const models = files.map(parseModel);
  const names = new Set(models.map((m) => m.modelName));

  // Mermaid erDiagram
  // Left-to-right layout fits a portrait page better. createdAt/updatedAt are omitted here (every
  // collection has them; the collection tables below say so) to keep the diagram readable.
  let mmd = `%% Generated by scripts/report/generate.mjs from server/src/models/*.ts - do not edit.\n%%{init: {"themeVariables": {"fontSize": "18px"}}}%%\nerDiagram\n  direction LR\n`;
  for (const m of models) {
    mmd += `  ${m.modelName} {\n    ObjectId _id PK\n`;
    for (const f of m.fields) {
      const t = f.isArray ? `${f.type.replace('[]', '')}_list` : f.type;
      const key = f.ref ? ' FK' : f.notes.includes('unique') ? ' UK' : '';
      mmd += `    ${t} ${f.name}${key}\n`;
    }
    mmd += `  }\n`;
  }
  for (const m of models) {
    for (const f of m.fields.filter((x) => x.ref)) {
      if (!names.has(f.ref)) continue;
      const card = f.isArray ? '}o--o{' : '||--o{';
      mmd += `  ${f.ref} ${card} ${m.modelName} : "${f.name}"\n`;
    }
  }
  fs.writeFileSync(path.join(REPORT, 'diagrams/er-diagram.mmd'), mmd);

  // Collection description tables
  let md = `${GENERATED_NOTE('server/src/models/*.ts')}\n\n`;
  for (const m of models) {
    md += `### Collection \`${m.collection}\` (model \`${m.modelName}\`)\n\n`;
    md += `Source: \`${m.file}\`.${m.timestamps ? ' Mongoose `timestamps` adds `createdAt` and `updatedAt`.' : ''}\n\n`;
    const intro = m.comments.filter((c) => !c.startsWith('This block')).join(' ').replace(/\s+/g, ' ').trim();
    if (intro) md += `${intro}\n\n`;
    md += mdTable(
      ['Field', 'Type', 'References', 'Constraints / notes'],
      [['`_id`', 'ObjectId', '—', 'primary key'], ...m.fields.map((f) => [`\`${f.name}\``, f.type, f.ref ?? '—', f.notes.join('; ') || '—'])],
      [24, 16, 16, 44],
    );
    md += '\n\n';
    if (m.indexes.length) {
      md += `Compound indexes: ${m.indexes.map((i) => `\`${i.keys}\`${i.unique ? ' (unique)' : ''}`).join(', ')}.\n\n`;
    }
  }
  replaceBlock('12-database-design.md', 'collections', md);
  return `${models.length} collections`;
}

