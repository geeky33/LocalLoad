#!/usr/bin/env node
/**
 * Regenerates every code-dependent part of docs/report/ from the source code.
 *
 *   node scripts/report/generate.mjs
 *
 * Markers used in the Markdown files (prose outside them is never touched):
 *   <!-- AUTO:name --> ... <!-- /AUTO:name -->          generated block
 *   <!-- SNIPPET: path/to/file.ts#Symbol --> ... <!-- /SNIPPET -->   code extracted from source
 *       Symbol = function / class / const / interface name, or Class.method
 *
 * Fails loudly (non-zero exit) if a marker, file or symbol cannot be found.
 * No third-party dependencies: Node.js >= 18 only.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const REPORT = path.join(ROOT, 'docs/report');
const rel = (p) => path.join(ROOT, p);
const read = (p) => fs.readFileSync(rel(p), 'utf8');
const fail = (msg) => {
  console.error(`\n[report:generate] ERROR: ${msg}\n`);
  process.exit(1);
};
const GENERATED_NOTE = (what) =>
  `<!-- This block is generated by scripts/report/generate.mjs from ${what}. Do not edit by hand; run scripts/build_report.sh. -->`;

/** Replace the content between <!-- AUTO:name --> and <!-- /AUTO:name --> in a report file. */
function replaceBlock(file, name, content) {
  const p = path.join(REPORT, file);
  const src = fs.readFileSync(p, 'utf8');
  const re = new RegExp(`(<!-- AUTO:${name} -->)[\\s\\S]*?(<!-- /AUTO:${name} -->)`);
  if (!re.test(src)) fail(`marker <!-- AUTO:${name} --> not found in docs/report/${file}`);
  fs.writeFileSync(p, src.replace(re, `$1\n${content.trim()}\n$2`));
}

/** Markdown pipe table. `widths` are relative column widths (pandoc sizes columns from the dash counts). */
const mdTable = (headers, rows, widths = headers.map(() => 10)) =>
  [
    `| ${headers.join(' | ')} |`,
    `|${widths.map((w) => '-'.repeat(Math.max(3, w))).join('|')}|`,
    ...rows.map((r) => `| ${r.map((c) => String(c).replace(/\|/g, '\\|')).join(' | ')} |`),
  ].join('\n');

