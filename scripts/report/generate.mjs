/** Find the end index of a balanced {...} block starting at `open`, skipping strings, templates and comments. */
function matchBrace(src, open) {
  let depth = 0;
  const stack = []; // template literal nesting
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    const n = src[i + 1];
    if (c === '/' && n === '/') {
      i = src.indexOf('\n', i);
      if (i === -1) return -1;
      continue;
    }
    if (c === '/' && n === '*') {
      i = src.indexOf('*/', i + 2) + 1;
      continue;
    }
    if (c === "'" || c === '"') {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === '\\') i++;
      continue;
    }
    if (c === '`') {
      // walk the template literal, recursing into ${ ... }
      for (i++; i < src.length && src[i] !== '`'; i++) {
        if (src[i] === '\\') i++;
        else if (src[i] === '$' && src[i + 1] === '{') {
          const end = matchBrace(src, i + 1);
          i = end;
        }
      }
      continue;
    }
    if (c === '{') depth++;
    if (c === '}') {
      depth--;
      if (depth === 0) return i;
    }
  }
  return stack.length ? -1 : -1;
}

/** Index of the ")" matching the "(" at `open`, skipping strings. */
function matchParen(src, open) {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === "'" || c === '"' || c === '`') {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === '\\') i++;
      continue;
    }
    if (c === '(') depth++;
    if (c === ')' && --depth === 0) return i;
  }
  return -1;
}

function extractSymbol(file, symbol) {
  const src = read(file);
  const [outer, inner] = symbol.split('.');
  let scopeStart = 0;
  let scopeEnd = src.length;
  let name = outer;
  if (inner) {
    const cls = src.search(new RegExp(`(^|\\n)(export\\s+)?class\\s+${outer}\\b`));
    if (cls === -1) fail(`class ${outer} not found in ${file}`);
    scopeStart = cls;
    scopeEnd = matchBrace(src, src.indexOf('{', cls));
    name = inner;
  }
  // A declaration at the start of a line: function / class / interface / const / class method.
  const decl = new RegExp(
    `\\n([ \\t]*)(?:export\\s+)?(?:default\\s+)?(?:(?:private|public|protected|static|async)\\s+)*(function\\s+${name}\\b|class\\s+${name}\\b|interface\\s+${name}\\b|(?:const|let)\\s+${name}\\b|${name}\\s*[(<])`,
    'g',
  );
  decl.lastIndex = Math.max(0, scopeStart - 1);
  const m = decl.exec(src);
  if (!m || m.index > scopeEnd) fail(`symbol "${symbol}" not found in ${file}`);
  const declStart = m.index + 1; // beginning of the declaration line
  let start = declStart;

  // Include the comment block directly above the declaration (JSDoc or // lines), nothing further up.
  const before = src.slice(0, start);
  const doc = before.match(/(\n[ \t]*\/\*\*(?:(?!\*\/)[\s\S])*\*\/[ \t]*\n|(?:\n[ \t]*\/\/[^\n]*)+\n)$/);
  if (doc) start -= doc[0].length - 1;

  // Find where the body starts: classes/interfaces at the first "{", functions after their parameter list.
  let end;
  if (/^(class|interface)\b/.test(m[2])) {
    end = matchBrace(src, src.indexOf('{', declStart));
  } else {
    const paren = src.indexOf('(', declStart + m[0].length - 2);
    const close = matchParen(src, paren);
    if (close === -1) fail(`unbalanced parameters for "${symbol}" in ${file}`);
    const after = src.slice(close + 1);
    const arrow = after.match(/^\s*(?::[^={;]*)?=>\s*/);
    if (arrow && src[close + 1 + arrow[0].length] !== '{') {
      end = src.indexOf(';', close); // expression-bodied arrow function
    } else {
      end = matchBrace(src, src.indexOf('{', close));
    }
  }
  if (end === -1) fail(`could not find the end of "${symbol}" in ${file}`);

  const text = src.slice(start, end + 1);
  const indent = Math.min(...text.split('\n').filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  const startLine = src.slice(0, start).split('\n').length;
  const endLine = src.slice(0, end).split('\n').length;
  return { code: text.split('\n').map((l) => l.slice(indent)).join('\n'), startLine, endLine };
}

function coreSnippets() {
  const file = path.join(REPORT, '13-core-logic.md');
  const src = fs.readFileSync(file, 'utf8');
  let count = 0;
  const out = src.replace(/<!-- SNIPPET: ([^#\s]+)#([\w.]+) -->[\s\S]*?<!-- \/SNIPPET -->/g, (_all, f, sym) => {
    if (!fs.existsSync(rel(f))) fail(`snippet source ${f} does not exist`);
    const { code, startLine, endLine } = extractSymbol(f, sym);
    count++;
    const lang = f.endsWith('.tsx') ? 'tsx' : 'typescript';
    return `<!-- SNIPPET: ${f}#${sym} -->\n*Source: \`${f}\`, lines ${startLine}–${endLine} (\`${sym}\`).*\n\n\`\`\`${lang}\n${code}\n\`\`\`\n<!-- /SNIPPET -->`;
  });
  fs.writeFileSync(file, out);
  return `${count} snippets`;
}

