function parseEnvExample(file) {
  const rows = [];
  let comment = [];
  for (const line of read(file).split('\n')) {
    if (line.startsWith('#')) comment.push(line.replace(/^#\s?/, ''));
    else if (/^\w+=/.test(line)) {
      const [k, ...v] = line.split('=');
      rows.push([`\`${k}\``, `\`${v.join('=')}\``, comment.join(' ') || '—']);
      comment = [];
    } else comment = [];
  }
  return rows;
}

